/**
 * JSON Schema and TypeScript declarations generated from the content schema.
 *
 * The generated `.d.ts` describes the `normalizeData` output of a valid entry: optional fields are absent rather than
 * `null` or `''`. Adapters and the admin read entry data through `normalizeData` before handing it out as these
 * types. `toJsonSchema` describes the raw frontmatter that validation accepts (where `null` / `''` are allowed).
 */
import { z } from 'zod';

import { BLOCK_KEY, type Collection, type Field, type Schema } from './schema';
import { buildDataSchema } from './validate';

export function toJsonSchema(collection: Collection): Record<string, unknown> {
  return z.toJSONSchema(buildDataSchema(collection), { target: 'draft-2020-12' }) as Record<string, unknown>;
}

const pascal = (key: string) => key.charAt(0).toUpperCase() + key.slice(1);

function array(type: string): string {
  return type.includes(' | ') ? `(${type})[]` : `${type}[]`;
}

function fieldType(field: Field): string {
  switch (field.type) {
    case 'string':
      return field.list ? 'string[]' : 'string';
    case 'text':
    case 'url':
    case 'color':
    case 'datetime':
    case 'markdown':
      return 'string';
    case 'boolean':
      return 'boolean';
    case 'number':
      return 'number';
    case 'json':
      return 'unknown';
    case 'select': {
      const union = field.options.map((o) => `'${o.value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`).join(' | ');
      return field.multiple ? array(union) : union;
    }
    case 'image':
      return '{ src: string; alt: string }';
    case 'reference': {
      const union = field.collections.map((c) => `\`${c}/\${string}\``).join(' | ');
      return field.multiple ? array(union) : union;
    }
    case 'object': {
      const type = objectType(field.fields);
      return field.list ? `${type}[]` : type;
    }
    case 'blocks': {
      const union = Object.entries(field.blocks)
        .map(([kind, block]) => objectType(block.fields, `${BLOCK_KEY}: '${quote(kind)}'`))
        .join(' | ');
      return array(union);
    }
  }
}

const quote = (v: string) => v.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

/** Inline type of nested fields: `{ title: string; image?: … }`; a nested `markdown` is a string. */
function objectType(fields: Record<string, Field>, first?: string): string {
  const parts = first === undefined ? [] : [first];
  for (const [key, field] of Object.entries(fields))
    parts.push(`${key}${field.required ? '' : '?'}: ${fieldType(field)}`);
  return `{ ${parts.join('; ')} }`;
}

export function generateTypes(schema: Schema): string {
  const lines = ['// Generated by editlet from the content schema. Do not edit.'];
  for (const [key, collection] of Object.entries(schema.collections)) {
    const name = pascal(key);
    lines.push('', `export interface ${name}Data {`);
    for (const [fieldKey, field] of Object.entries(collection.fields)) {
      if (field.type === 'markdown') continue;
      lines.push(`  ${fieldKey}${field.required ? '' : '?'}: ${fieldType(field)};`);
    }
    lines.push('  draft?: boolean;', '}');
    lines.push(
      '',
      `export interface ${name}Entry {`,
      `  collection: '${key}';`,
      '  slug: string;',
      `  data: ${name}Data;`,
      '  body: string;',
      '}',
    );
  }
  lines.push('', 'export interface EntryMap {');
  for (const key of Object.keys(schema.collections)) lines.push(`  ${key}: ${pascal(key)}Entry;`);
  lines.push('}');
  return `${lines.join('\n')}\n`;
}
