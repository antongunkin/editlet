import { access, cp, mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, extname, join } from 'node:path';

import { ADMIN_CONFIG_FILE, type AdminConfig } from '../admin/config';
import { isHiddenContentPath, isImagePath } from '../core/paths';
import { DEFAULT_SCHEMA_PATH, listFiles, loadProjectSchema } from '../node/fs';

export const GENERATED_MARKER = '.editlet-generated';

async function exists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function adminSource(pkg: string): Promise<string> {
  const dist = join(pkg, 'admin', 'dist');
  return (await exists(join(dist, 'index.html'))) ? dist : join(pkg, 'next', 'stub');
}

const RM = { recursive: true, force: true, maxRetries: 3 } as const;

async function assertOwned(out: string): Promise<void> {
  if (!(await exists(join(out, GENERATED_MARKER)))) {
    throw new Error(`Refusing to overwrite ${out}: it was not generated by Editlet (no ${GENERATED_MARKER} marker).`);
  }
}

/** Rebuilds the admin part of `public/editlet/` (everything except `content/`), including `config.json`. Used once per prepare. */
export async function syncAdminOnly(root: string, pkgDir: string, config: AdminConfig): Promise<void> {
  const out = join(root, 'public', 'editlet');
  if (await exists(out)) {
    await assertOwned(out);
    for (const name of await readdir(out)) {
      if (name !== GENERATED_MARKER && name !== 'content') await rm(join(out, name), RM);
    }
  } else {
    await mkdir(out, { recursive: true });
    await writeFile(join(out, GENERATED_MARKER), 'Generated by editlet/next. Safe to delete.\n');
  }
  await cp(await adminSource(pkgDir), out, { recursive: true });
  await writeFile(join(out, ADMIN_CONFIG_FILE), `${JSON.stringify(config, null, 2)}\n`);
}

/** Rebuilds only `public/editlet/content/` (the images under `contentDir`); the admin files are not touched. */
export async function syncContent(root: string, schemaPath: string = DEFAULT_SCHEMA_PATH): Promise<void> {
  const out = join(root, 'public', 'editlet');
  await assertOwned(out);
  const schema = await loadProjectSchema(root, schemaPath);
  const files = await listFiles(root, schema.contentDir);
  await rm(join(out, 'content'), RM);
  for (const file of files) {
    if (!isImagePath(file) || isHiddenContentPath(schema, file)) continue;
    const target = join(out, 'content', file.slice(schema.contentDir.length + 1));
    await mkdir(dirname(target), { recursive: true });
    await cp(join(root, file), target);
  }
}

/** Full rebuild of `<root>/public/editlet/`: the admin bundle plus the content images. */
export async function syncPublicDir(
  root: string,
  schemaPath: string = DEFAULT_SCHEMA_PATH,
  pkgDir: string,
  config: AdminConfig,
): Promise<void> {
  await syncAdminOnly(root, pkgDir, config);
  await syncContent(root, schemaPath);
}

/** Watch events worth a content re-sync: image files, or paths without an extension (directory moves/deletes). */
export function shouldResyncContent(filename: string | null): boolean {
  if (!filename) return true;
  return isImagePath(filename) || extname(filename) === '';
}
